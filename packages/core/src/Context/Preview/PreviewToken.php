<?php

declare(strict_types=1);

namespace Preflow\Core\Context\Preview;

use Preflow\Core\Context\Contexts;
use Preflow\Core\Context\RenderContext;
use Preflow\Core\Context\RoleView;
use Preflow\Core\Context\SyntheticIdentity;
use Preflow\Core\Context\Viewer;
use Preflow\Core\Http\Session\SessionInterface;
use Preflow\Core\Identity;
use Preflow\Core\Security\AppKey;
use Psr\Http\Message\ServerRequestInterface;

/**
 * Signed preview tokens: a staff member's preview (working copies, a role view) hands its reading
 * mode to the follow-up requests the previewed page makes (htmx actions, live parts, lazy
 * fragments), and to nobody else.
 *
 * A token is `v1.{payload}.{sig}.{bind}`, each part base64url without padding:
 * - payload: JSON `{"r":[population,[roles]]|null,"l":locale,"w":bool,"i":[guard,id],"q":[permissions],"e":expiry,"j":id}`
 *   (a role view's `q` always names PreviewGate::VIEW_AS);
 * - sig: HMAC-SHA256(key, "v1.{payload}"): the claims are this app's and unchanged;
 * - bind: HMAC-SHA256(key, "v1.{payload}.{sha256 hex of the session id}"): issued for this session.
 * The key is HMAC-SHA256(app key, 'preflow/preview-token/v1'), so it signs nothing else (component
 * tokens, share links, stateless CSRF tokens use their own). The session id is in neither the
 * payload nor the token, only in the MAC input. Both MACs are compared in constant time.
 *
 * A token holds when (verify(), in this order): the app key is real (else 'disabled'); it has the
 * format and at most MAX_LENGTH bytes ('malformed'); sig matches ('signature'); bind matches the
 * request's session ('session': another browser, or the session was regenerated by a sign-out or
 * sign-in); the payload is exactly the claims with their types ('malformed'); it has not expired and
 * claims no more than MAX_TTL ('expired'); the identity signed in now with the issuer's guard is
 * the issuer ('identity': a member signed in beside the staff member who issued it does not stop
 * it). admit() then asks the PreviewGate, as the issuer's guard, whether the issuer still holds
 * every required permission (for a role view: view-as included) ('permission'). Whoever holds
 * view-as may view as any role, also one with more rights than their own (owner ruling, 0.81). admit() is the one entry outside core: verify() alone skips the gate.
 * Within its session and lifetime the issuer
 * may replay it as often as needed (fragments need it); its id (jti) is for logs.
 *
 * The derived key is never part of the signer's state (it is kept in a static WeakMap keyed by
 * the signer), so no dump, var_export(), (array) cast or serialize() of a signer shows it; a
 * dump shows only whether it is enabled, and a signer cannot be serialized.
 *
 * @since 0.81.0
 */
final class PreviewToken
{
    /** The query parameter that carries a token. */
    public const string PARAM = '_preview';

    /** The request header that carries a token. */
    public const string HEADER = 'X-Preflow-Preview';

    /** Seconds a token lives by default. */
    public const int TTL = 900;

    /** The longest a token may live, in seconds; longer TTLs are clamped to it. */
    public const int MAX_TTL = 3600;

    /** The longest token read, in bytes. */
    public const int MAX_LENGTH = 2048;

    private const string VERSION = 'v1';

    private const string KEY_PURPOSE = 'preflow/preview-token/v1';

    /** The token's shape; its length is bounded by MAX_LENGTH alone, which issue() and verify() both apply. */
    private const string FORMAT = '/^v1\.([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]{43})\.([A-Za-z0-9_-]{43})$/D';

    private const string LOCALE = '/^[A-Za-z0-9]{1,8}(?:[_-][A-Za-z0-9]{1,8}){0,4}$/D';

    private const array CLAIMS = ['e', 'i', 'j', 'l', 'q', 'r', 'w'];

    /** @var \WeakMap<self, string>|null each signer's derived key, outside its object state */
    private static ?\WeakMap $keys = null;

    private readonly bool $enabled;

    /** @param string $appKey app.key; one that fails AppKey::canSign() (empty, short, public) disables tokens */
    public function __construct(#[\SensitiveParameter] string $appKey)
    {
        $this->enabled = AppKey::canSign($appKey);
        self::$keys ??= new \WeakMap();
        self::$keys[$this] = hash_hmac('sha256', self::KEY_PURPOSE, $appKey, true);
    }

    /** Whether tokens are issued and trusted: not with an app key that fails AppKey::canSign(). */
    public function enabled(): bool
    {
        return $this->enabled;
    }

    /**
     * A token granting $ctx's reading mode (its role view or an anonymous visitor, its locale,
     * working copies or not) to $issuer, signed in with the guard $guard, in the session
     * $sessionId, for $ttl seconds (clamped to MAX_TTL) from the current render's clock
     * (Contexts::clock()).
     *
     * @param list<string> $requires the permissions $issuer was checked for; re-checked at each use.
     *        A role view's must name PreviewGate::VIEW_AS, so taking that permission away ends it.
     *
     * @throws \LogicException when tokens are disabled, or there is no session to bind to
     * @throws \InvalidArgumentException for a ttl below 1, no or an empty permission, a role view
     *         without PreviewGate::VIEW_AS, an issuer that is a role view or has no id or guard, a
     *         $ctx whose viewer is a real account, which reads as of a date or is frozen with at(),
     *         or a token longer than MAX_LENGTH
     */
    public function issue(RenderContext $ctx, #[\SensitiveParameter] string $sessionId, string $guard, Identity $issuer, array $requires, int $ttl = self::TTL): string
    {
        if (!$this->enabled) {
            throw new \LogicException('Preview tokens need a real app.key (at least 32 bytes, not a public default).');
        }
        if ($sessionId === '') {
            throw new \LogicException('A preview token is bound to a session; there is none.');
        }
        if ($ttl < 1) {
            throw new \InvalidArgumentException("A preview token lives at least one second, got {$ttl}.");
        }
        $issuerId = $issuer->getAuthId();
        if ($guard === '' || $issuerId === '' || $issuer instanceof SyntheticIdentity || str_starts_with($issuerId, SyntheticIdentity::PREFIX)) {
            throw new \InvalidArgumentException('A preview token is issued to a signed-in staff member, not to a role view or nobody.');
        }
        $requires = array_values($requires);
        if ($requires === [] || array_filter($requires, static fn (mixed $p): bool => !is_string($p) || $p === '') !== []) {
            throw new \InvalidArgumentException('A preview token names the permissions its issuer was checked for (at least one, each a name).');
        }
        if (!$ctx->viewer->isAnonymous() && !$ctx->viewer->isSynthetic()) {
            throw new \InvalidArgumentException("A preview token grants a visitor's or a role's view, not a real account's.");
        }
        if ($ctx->reads->at !== null) {
            throw new \InvalidArgumentException('A preview token cannot grant reads as of a date.');
        }
        if ($ctx->isFrozen()) {
            throw new \InvalidArgumentException('A preview token cannot grant a frozen time: its follow-ups render at the real time.');
        }
        if ($ctx->viewer->roleView?->guard !== null && $ctx->viewer->roleView->guard !== $guard) {
            throw new \InvalidArgumentException('A role view\'s preview token is issued to the guard the role view names.');
        }
        if ($ctx->viewer->isSynthetic() && !in_array(PreviewGate::VIEW_AS, $requires, true)) {
            throw new \InvalidArgumentException('A role view\'s preview token must require ' . PreviewGate::VIEW_AS . ', so taking it away ends the role view.');
        }
        if (preg_match(self::LOCALE, $ctx->locale) !== 1) {
            throw new \InvalidArgumentException('A preview token needs a locale code.');
        }
        $role = $ctx->viewer->roleView;
        $claims = [
            'r' => $role === null ? null : [$role->population, $role->roles],
            'l' => $ctx->locale,
            'w' => $ctx->reads->readsWorkingCopies(),
            'i' => [$guard, $issuerId],
            'q' => $requires,
            'e' => Contexts::clock()->now()->getTimestamp() + min($ttl, self::MAX_TTL),
            'j' => bin2hex(random_bytes(16)),
        ];
        $signed = self::VERSION . '.' . self::encode(json_encode($claims, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR));
        $token = $signed . '.' . self::encode($this->sig($signed)) . '.' . self::encode($this->bind($signed, $sessionId));
        if (strlen($token) > self::MAX_LENGTH) {
            throw new \InvalidArgumentException('The preview token would be longer than ' . self::MAX_LENGTH . ' bytes (too many roles or permissions).');
        }

        return $token;
    }

    /**
     * The claims of $token for a request in the session $sessionId by $viewer (its identity signed
     * in with the issuer's guard must be the issuer), at $now. Checks everything but the
     * permissions: use admit(), which asks the gate too.
     *
     * @internal core and its tests only; outside core, admit() (a guard rule enforces it)
     *
     * @throws PreviewTokenRejected with the first reason it fails for (see the class docblock)
     */
    public function verify(#[\SensitiveParameter] string $token, #[\SensitiveParameter] string $sessionId, Viewer $viewer, \DateTimeImmutable $now): PreviewClaims
    {
        if (!$this->enabled) {
            throw new PreviewTokenRejected('disabled');
        }
        if (strlen($token) > self::MAX_LENGTH || preg_match(self::FORMAT, $token, $parts) !== 1) {
            throw new PreviewTokenRejected('malformed');
        }
        [, $payload, $sig, $bind] = $parts;
        $signed = self::VERSION . '.' . $payload;
        if (!hash_equals(self::encode($this->sig($signed)), $sig)) {
            throw new PreviewTokenRejected('signature');
        }
        if ($sessionId === '' || !hash_equals(self::encode($this->bind($signed, $sessionId)), $bind)) {
            throw new PreviewTokenRejected('session');
        }
        // Only a payload this app signed is parsed.
        $claims = self::claims($payload, $token) ?? throw new PreviewTokenRejected('malformed');
        $left = $claims->expires - $now->getTimestamp();
        if ($left <= 0 || $left > self::MAX_TTL) {
            throw new PreviewTokenRejected('expired');
        }
        $current = $viewer->isSynthetic() ? null : $viewer->for($claims->issuerGuard);
        $id = $current?->getAuthId();
        if ($id === null || $current instanceof SyntheticIdentity || str_starts_with($id, SyntheticIdentity::PREFIX) || !hash_equals($claims->issuer, $id)) {
            throw new PreviewTokenRejected('identity');
        }

        return $claims;
    }

    /**
     * A follow-up request's admission: verify() against $current's viewer at the current render's
     * clock (Contexts::clock()), then $gate, asked as the issuer (the viewer with the issuer's guard
     * as its primary one), for every required permission (a role view's include VIEW_AS, so taking
     * that away ends it; the role itself is not compared with the issuer's rights). Call it on every request that carries a token, in the request's own
     * frame, before any role view starts (the role view is rebuilt from its names here, never
     * taken from a serialized context).
     *
     * @param RenderContext $current the request's own context (its real viewer, before apply())
     *
     * @throws PreviewTokenRejected for any reason verify() gives, or 'permission'
     */
    public function admit(#[\SensitiveParameter] string $token, #[\SensitiveParameter] string $sessionId, RenderContext $current, PreviewGate $gate): PreviewClaims
    {
        $claims = $this->verify($token, $sessionId, $current->viewer, Contexts::clock()->now());
        $issuer = $current->as(new Viewer($current->viewer->identities, $claims->issuerGuard));
        // A role view's token requires PreviewGate::VIEW_AS (issue() and the parser insist), so this
        // also ends a role view whose issuer lost it. Which role is not compared with the issuer's
        // own rights: whoever may view as roles may view as any (owner ruling, 0.81).
        if (!$gate->allows($issuer, $claims->requires)) {
            throw new PreviewTokenRejected('permission');
        }

        return $claims;
    }

    /**
     * $ctx (the preview's context) with a PreviewGrant whose token is issued to the staff request's
     * primary identity and its guard (its RenderContext attribute's viewer, else the current
     * render's) in its session (its SessionInterface attribute), for $requires.
     *
     * @param list<string> $requires the permissions the staff member was checked for (a role view: PreviewGate::VIEW_AS among them)
     *
     * @throws \LogicException when tokens are disabled, the request has no started session, or nobody (or a role view) is signed in
     * @throws \InvalidArgumentException see issue()
     */
    public function grant(RenderContext $ctx, ServerRequestInterface $staffRequest, array $requires): RenderContext
    {
        $session = $staffRequest->getAttribute(SessionInterface::class);
        if (!$session instanceof SessionInterface || !$session->isStarted() || $session->getId() === '') {
            throw new \LogicException("A preview token is bound to the staff member's session; the request has none.");
        }
        $staff = $staffRequest->getAttribute(RenderContext::class);
        $viewer = ($staff instanceof RenderContext ? $staff : Contexts::current())->viewer;
        $issuer = $viewer->isSynthetic() ? null : $viewer->primary();
        $guard = $issuer === null ? false : array_search($issuer, $viewer->identities, true);
        if ($issuer === null || $guard === false) {
            throw new \LogicException('A preview token is issued to a signed-in staff member; nobody is signed in.');
        }

        return $ctx->with(new PreviewGrant($this->issue($ctx, $session->getId(), (string) $guard, $issuer, $requires)));
    }

    /** @return array{enabled: bool} never the key */
    public function __debugInfo(): array
    {
        return ['enabled' => $this->enabled];
    }

    /** @throws \LogicException always: a signer holds a key */
    public function __serialize(): array
    {
        throw new \LogicException('A preview token signer cannot be serialized.');
    }

    /** @param array<mixed> $data */
    public function __unserialize(array $data): void
    {
        throw new \LogicException('A preview token signer cannot be unserialized.');
    }

    private function sig(string $signed): string
    {
        return hash_hmac('sha256', $signed, $this->key(), true);
    }

    private function bind(string $signed, #[\SensitiveParameter] string $sessionId): string
    {
        return hash_hmac('sha256', $signed . '.' . hash('sha256', $sessionId), $this->key(), true);
    }

    private function key(): string
    {
        return self::$keys[$this] ?? throw new \LogicException('A preview token signer has no key.');
    }

    /** The claims of a signed payload; null unless it is exactly the claims with their types. */
    private static function claims(string $payload, #[\SensitiveParameter] string $token): ?PreviewClaims
    {
        $json = base64_decode(strtr($payload, '-_', '+/'), true);
        if ($json === false || self::encode($json) !== $payload) {
            return null;
        }
        try {
            $c = json_decode($json, true, 4, JSON_THROW_ON_ERROR | JSON_BIGINT_AS_STRING);
        } catch (\JsonException) {
            return null;
        }
        if (!is_array($c) || array_is_list($c) && $c !== []) {
            return null;
        }
        $keys = array_map('strval', array_keys($c));
        sort($keys, SORT_STRING);
        if ($keys !== self::CLAIMS) {
            return null;
        }
        $role = self::role($c['r']);
        if ($role === false
            || !is_string($c['l']) || preg_match(self::LOCALE, $c['l']) !== 1
            || !is_bool($c['w'])
            || !is_array($c['i']) || !array_is_list($c['i']) || count($c['i']) !== 2
            || !is_string($c['i'][0]) || $c['i'][0] === '' || !is_string($c['i'][1]) || $c['i'][1] === '' || str_starts_with($c['i'][1], SyntheticIdentity::PREFIX)
            || !is_array($c['q']) || $c['q'] === [] || !array_is_list($c['q'])
            || array_filter($c['q'], static fn (mixed $p): bool => !is_string($p) || $p === '') !== []
            || ($role !== null && !in_array(PreviewGate::VIEW_AS, $c['q'], true))
            || !is_int($c['e']) || $c['e'] <= 0
            || !is_string($c['j']) || preg_match('/^[0-9a-f]{32}$/D', $c['j']) !== 1) {
            return null;
        }

        // The role view is the issuer's: viewed by someone signed in with the issuer's guard.
        return new PreviewClaims($role?->by($c['i'][0]), $c['l'], $c['w'], $c['i'][1], $c['i'][0], $c['q'], $c['e'], $c['j'], $token);
    }

    /** The role view of claim r: null for none, false when it is not [population, [roles]] in canonical form. */
    private static function role(mixed $r): RoleView|false|null
    {
        if ($r === null) {
            return null;
        }
        if (!is_array($r) || !array_is_list($r) || count($r) !== 2 || !is_string($r[0]) || !is_array($r[1]) || !array_is_list($r[1])) {
            return false;
        }
        foreach ($r[1] as $role) {
            if (!is_string($role)) {
                return false;
            }
        }
        try {
            $view = new RoleView($r[0], $r[1]);
        } catch (\InvalidArgumentException) {
            return false;
        }

        // Canonical only: the roles as RoleView keeps them (sorted, each once).
        return $view->roles === $r[1] ? $view : false;
    }

    private static function encode(string $bytes): string
    {
        return rtrim(strtr(base64_encode($bytes), '+/', '-_'), '=');
    }
}
