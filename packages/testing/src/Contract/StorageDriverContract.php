    /**
     * Stored values read as a whole number (Condition::wholeNumber(), since 0.90 on every
     * storage): text is a number only as `-?digits` or `-?digits.digits`, cut to the digits before
     * the dot; any other text is 0; null and '' are none. Text sits in a text column (`n`), as a
     * table made before typed columns holds it (a number column would convert some of it when it
     * is saved); a number column (`v`) holds numbers with decimals and large ones. Each value is
     * checked by comparisons and by an Add, on every path conditionalWrites() runs.
     */
    public function test_number_text_reads_the_same_on_every_storage(): void
    {
        $texts = [
            ' 3' => 0, '3 ' => 0, '  ' => 0, "3\n" => 0, "3\0" => 0, '1e3' => 0, '.5' => 0, '0x1A' => 0, '+3' => 0, '-' => 0,
            '1.2.3' => 0, 'abc' => 0, '-3.7' => -3, '-0.5' => 0, '3.' => 3, '3.0' => 3, '007' => 7,
            '3.99999999999999999999' => 3, '-3.99999999999999999999' => -3, '9007199254740993.5' => 9007199254740993, '' => null,
        ];
        $records = ['none' => ['n', null, null]];
        $i = 0;
        foreach ($texts as $text => $number) {
            $records['t' . $i++] = ['n', (string) $text, $number];
        }
        foreach ([[3.9, 3], [-3.9, -3], [1e15, 1000000000000000], [-2.5e15, -2500000000000000], [7, 7]] as [$stored, $number]) {
            $records['v' . $i++] = ['v', $stored, $number];
        }

        $this->createType('numtext', ['uuid' => 'exact', 'n' => 'exact', 'v' => 'number', 'mark' => 'exact']);
        $models = sys_get_temp_dir() . '/contract_models_' . bin2hex(random_bytes(4));
        @mkdir($models, 0777, true);
        try {
            $registry = new \Preflow\Data\TypeRegistry($models);
            $def = $registry->define([
                'key' => 'numtext', 'table' => 'numtext', 'storage' => 'default', 'id_field' => 'uuid',
                'fields' => ['n' => ['type' => 'string'], 'v' => ['type' => 'integer'], 'mark' => ['type' => 'string']],
            ]);
            $paths = ['driver' => $this->driver, 'checked in PHP' => new PlainDriver($this->driver)];
            if ($this->driver instanceof RunsSql) {
                $paths['RunsSql only'] = self::sqlOnly($this->driver);
            }
            foreach ($paths as $path => $driver) {
                $dm = new \Preflow\Data\DataManager(['default' => $driver], 'default', $registry);
                foreach ($records as $id => [$field, $stored, $number]) {
                    $this->driver->save('numtext', $id, ['uuid' => $id, 'n' => null, 'v' => null, 'mark' => null, $field => $stored]);
                    $what = "{$path}: {$field} " . var_export($stored, true) . ' reads as ' . json_encode($number);
                    $writes = function (\Preflow\Data\Condition $when, string $how) use ($dm, $def, $id, $what): bool {
                        $wrote = $dm->updateWhen($def, $id, $when, ['mark' => 'w']);
                        $this->assertSame($wrote ? 'w' : null, ($this->driver->findOne('numtext', $id) ?? [])['mark'] ?? null, "{$what} ({$how}): stored");
                        $this->driver->save('numtext', $id, ['uuid' => $id, 'mark' => null]);

                        return $wrote;
                    };
                    if ($number === null) {
                        foreach (['=', '!=', '<', '>', '<=', '>='] as $operator) {
                            $this->assertFalse($writes(\Preflow\Data\Condition::where($field, $operator, 0), $operator), "{$what}: no value is never {$operator} 0");
                        }
                        $this->assertFalse($writes(\Preflow\Data\Condition::where($field, 'IN', [0]), 'IN'), "{$what}: no value is in no list");
                    } else {
                        $this->assertTrue($writes(\Preflow\Data\Condition::where($field, '=', $number), '='), $what);
                        $this->assertFalse($writes(\Preflow\Data\Condition::where($field, '!=', $number), '!='), $what);
                        $this->assertTrue($writes(\Preflow\Data\Condition::where($field, '<', $number + 1), '<'), $what);
                        $this->assertTrue($writes(\Preflow\Data\Condition::where($field, '>', $number - 1), '>'), $what);
                        $this->assertTrue($writes(\Preflow\Data\Condition::where($field, 'IN', [$number, 99]), 'IN'), $what);
                    }
                    $this->assertTrue($dm->updateWhen($def, $id, \Preflow\Data\Condition::all(), [$field => new \Preflow\Data\Add(1)]), "{$what}: Add");
                    $this->assertNumber(($number ?? 0) + 1, ($this->driver->findOne('numtext', $id) ?? [])[$field] ?? null);
                    $this->driver->delete('numtext', $id);
                }
                // An Add past the 64-bit whole numbers is refused (since 0.90) and writes nothing.
                foreach ([[(string) PHP_INT_MAX, 1], [(string) PHP_INT_MIN, -1]] as [$edge, $amount]) {
                    $this->driver->save('numtext', 'edge', ['uuid' => 'edge', 'n' => $edge, 'v' => null, 'mark' => null]);
                    try {
                        $dm->updateWhen($def, 'edge', \Preflow\Data\Condition::all(), ['n' => new \Preflow\Data\Add($amount), 'mark' => 'w']);
                        $this->fail("{$path}: adding {$amount} to {$edge} was not refused");
                    } catch (\OverflowException $e) {
                        $this->assertStringContainsString('[n]', $e->getMessage(), $path);
                    }
                    $row = $this->driver->findOne('numtext', 'edge') ?? [];
                    $this->assertSame($edge, (string) ($row['n'] ?? ''), "{$path}: {$edge} stays");
                    $this->assertNull($row['mark'] ?? null, "{$path}: nothing written");
                    $this->assertFalse($dm->updateWhen($def, 'edge', \Preflow\Data\Condition::where('mark', '=', 'x'), ['n' => new \Preflow\Data\Add($amount)]), "{$path}: a condition that does not hold is no overflow");
                    $this->assertTrue($dm->updateWhen($def, 'edge', \Preflow\Data\Condition::all(), ['n' => new \Preflow\Data\Add(-$amount)]), "{$path}: back towards 0 is fine");
                    $this->assertSame((string) ((int) $edge - $amount), (string) (($this->driver->findOne('numtext', 'edge') ?? [])['n'] ?? ''), $path);
                    $this->driver->delete('numtext', 'edge');
                }
                // Several Adds in one write: the one out of range refuses the whole write.
                $this->driver->save('numtext', 'edge', ['uuid' => 'edge', 'n' => (string) (PHP_INT_MAX - 5), 'v' => 1, 'mark' => null]);
                try {
                    $dm->updateWhen($def, 'edge', \Preflow\Data\Condition::all(), ['n' => new \Preflow\Data\Add(10), 'v' => new \Preflow\Data\Add(1)]);
                    $this->fail("{$path}: adding 10 to MAX - 5 was not refused");
                } catch (\OverflowException $e) {
                    $this->assertStringContainsString('[n]', $e->getMessage(), $path);
                }
                $row = $this->driver->findOne('numtext', 'edge') ?? [];
                $this->assertSame((string) (PHP_INT_MAX - 5), (string) ($row['n'] ?? ''), "{$path}: the field out of range stays");
                $this->assertNumber(1, $row['v'] ?? null);
                $this->driver->delete('numtext', 'edge');
            }
        } finally {
            @rmdir($models);
        }
    }

