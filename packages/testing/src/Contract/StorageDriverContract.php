/**
 * What every StorageDriver does, as tests. Extend it, implement the two hooks, and run it with
 * PHPUnit:
 *
 *     final class MyDriverContractTest extends StorageDriverContract
 *     {
 *         protected function createDriver(): StorageDriver
 *         {
 *             return new MyDriver(...);
 *         }
 *
 *         protected function createType(string $type, array $fields): void
 *         {
 *             // e.g. CREATE TABLE $type (...)
 *         }
 *     }
 *
 * - createDriver() is called once per test, in setUp(), before any createType(). Each test needs
 *   an empty store: a fresh in-memory database, a temporary directory, or a database the test
 *   class empties in setUp() and tearDown().
 * - createType() prepares the store for one type (an SQL driver creates the table; a store
 *   without a schema does nothing). $fields maps each field name to `exact`, `text`,
 *   `short_text`, `number`, `boolean` or `json`. `text` is a text field (since 0.78): =, !=, IN,
 *   NOT IN, ranges, ORDER BY, grouping and a unique index compare it by the text rule below;
 *   `short_text` is a text field in a bounded, indexed column (a unique or indexed string; an SQL
 *   store makes the index); `exact` is an exact text field (an id, a key, a code; before 0.78 this
 *   kind was `string`, renamed since its comparison changed). The first field is the id field and the primary key: an `exact` id is
 *   given by the caller; a `number` id is generated by the store (auto increment) and only
 *   used when supportsAutoIds() is true. Every other field takes null.
 *
 * Values read back may come in the store's own representation, as DataManager accepts them:
 * a number as an int, a float or a numeric string; a boolean as true/false, 1/0 or "1"/"0";
 * a `json` field (saved as an array) as that array or as JSON text, where the keys of an object
 * need not keep their order (a list's order and every value must); null as null or a missing
 * key. Strings come back exactly as saved.
 *
 * Query semantics a driver implements (as SQLite and MySQL do):
 * - Text matching: `LIKE`, `NOT LIKE`, `CONTAINS`, search(), searchLoose() and so ⌘K's loose-search
 *   set compare text character by character, as MySQL/MariaDB's LIKE does under an
 *   accent-insensitive, case-insensitive collation: case and accents are ignored, and so are width
 *   and compatibility forms ("ＡＢＣ", "①" are "abc", "1"). "über", "ÜBER" and "uber" find "Über",
 *   "elise" finds "Élise", "istanbul" finds "İstanbul", "ore" finds "Øre", "lodz" finds "Łódź"; the
 *   Kelvin sign is a k and the long s ſ an s; ß is one letter ("strasse" does not find "Straße",
 *   "STRAẞE" does), and so are æ ("aegir" does not find "Ægir") and ı ("ilik" does not find
 *   "ılık"). `%` matches any text, `_` one character (an umlaut is one). Text is compared as
 *   stored (a decomposed "Ü" is not promised to match). Preflow\Data\Text\TextMatch is the rule
 *   in PHP (like(), contains(), matchFold()); its matching table is derived from the server.
 *   (since 0.78, accents ignored since 0.78.1; SQLite needs its Unicode ulike(), see
 *   SqliteDialect::prepare(), MySQL an accent-insensitive collation in the query, see
 *   MysqlDialect::likeSql()).
 * - Exact comparisons (since 0.78): `=`, `!=`, `IN`, `NOT IN`, ranges and ORDER BY on a `text`
 *   field, and GROUP BY, COUNT(DISTINCT), MIN and MAX over it, compare the whole text by the
 *   text rule (TextMatch::equals()/compare()), which respects accents: "müller" is "MÜLLER",
 *   "muller" is not (where LIKE '%muller%' finds both); "strasse" is not "Straße"; the Kelvin sign
 *   is a k; "istanbul" is not "İstanbul"; texts sort as "Apfel", "äpfel", "eagle", "Émile",
 *   "Zebra". A unique index on a `text` field refuses a case variant and takes an
 *   accent variant. An `exact` field compares exactly ("ab" is not "Ab"). The tests name the text
 *   fields on each query (Query::compareAsText(), as QueryBuilder does from a type): a store
 *   without columns (JSON) compares by them, an SQL store by its columns' collation.
 * - search() and the `CONTAINS` of whereAny() find a term in a text, and in a list (a `json`
 *   field saved as a list) when one of its values holds it, slashes and umlauts as they are.
 * - `HAS` (whereAny) matches a field holding one of the given ids: a single id, a list of ids,
 *   or JSON text of a list (a multiple relation or asset stored before 0.89), mixed in one table.
 * - A null field matches only `where(field, null)` (IS NULL); `=`, `!=`, `<>`, `<`, `>`, `<=`,
 *   `>=`, `LIKE`, `NOT LIKE`, `IN` and `NOT IN` never match it. `!= null` / `<> null` is IS NOT
 *   NULL. An empty `IN` list matches nothing, an empty `NOT IN` list everything (nulls too).
 * - Numbers compare and sort as numbers. `where()` binds tighter than `orWhere()`, as AND before
 *   OR in SQL. `total()` counts every match, ignoring limit and offset.
 * - save() of an existing id updates the fields it is given and keeps the others; a field given as
 *   null is stored as null (@since 0.78). delete() of a missing id does nothing.
 * - A driver with InsertsNew (@since 0.79.0) writes a record only while no record has its id, and says
 *   which: true when written, false when the id exists (the stored record stays as it is). A
 *   given int id is written as it is, and a store that generates ids gives the next record
 *   generated after it an id of its own, not the given one (@since 0.80.0).
 * - A driver with ConditionalUpdates (@since 0.77) writes only the named fields, and only while the
 *   version field holds the expected whole number (as text or number; null: none, NULL or '', and
 *   never 0); a match that changes no value is still a match.
 * - Conditional writes (@since 0.89.0): DataManager::updateWhen() and deleteWhen() write or delete
 *   one record only while a Preflow\Data\Condition holds on it, as Condition describes (whole
 *   numbers, exact texts, two fields, "is empty", all/any; an Add adds to a number), and false/null
 *   when it does not or the record is missing; a skipping render writes nothing, a refusing one
 *   throws when the condition holds. Each case runs through the driver (ConditionalWrites, when it
 *   implements it, compiles the condition) and through PlainDriver on the same store (the PHP
 *   check), so both must agree. Text in a field compared as a number reads as
 *   Condition::wholeNumber() reads it (@since 0.90: ' 3', '1e3', '.5', '0x1A' are 0, '-3.7' and
 *   '-3.99999999999999999999' are -3, '' and null none), and a number with decimals or one of 1e15
 *   in a number column reads as its whole part, in comparisons and in an Add. An Add past the
 *   64-bit whole numbers throws an OverflowException and writes nothing.
 * - An empty id is '', 0 or '0' (as PdoDriver and DataManager treat it): save() with one inserts
 *   a record whose id the store generates, and lastInsertId() returns it.
 * - Change dates (@since 0.84.0): DataManager writes every record of a type with its change date
 *   (Preflow\Data\ChangeDates: the system key `_updated_at`, ISO 8601 text in UTC; a type's own
 *   updated field is content it never writes). A driver stores and reads it as any other key, and sorts by it as text; nothing
 *   else is asked of it. An SQL store holds it in a column of its own, which `preflow migrate`
 *   adds to the tables it makes (the tests create it as an `exact` field); a store without a
 *   schema takes the key. DataManager writes it only to a store with DescribesColumns whose
 *   hasColumn() says the table has it; a store without that capability gets no change date (its
 *   records are written as before 0.84), and the change-date tests skip.
 *   A store that knows when each record was written by its own means (a file's time) may say so
 *   (WriteTimes): the backfill of `preflow migrate` uses it for records written before 0.84.
 *
 * Optional hooks, for stores that cannot do something generic:
 * - supportsAutoIds() (default true): false skips the test that saves with each empty id ('',
 *   0, '0') and reads the new id from lastInsertId() (the JSON file driver needs the id from
 *   the caller).
 * - reopenDriver() (default null): a second driver on the same store, made in a forked child
 *   process (its own connection or file handles), for the tests that write from several
 *   processes at once; null skips them (an in-memory store cannot be shared).
 * - declareFullText() (default: nothing): makes a type's fields scorable together, as the store
 *   needs it (MySQL: a FULLTEXT index over exactly those columns), for the RankedSearch tests.
 * - declareUnique() (default: skips): a unique index over one field, for a store that guards
 *   unique fields itself (UniqueIndexes); a store without one leaves uniqueness to DataManager's
 *   check (Validation\Unique), which UniqueScenarios in preflow/data pins on every built-in store.
 * - emptyDriver() (default null): a driver on a second, empty store of the same kind, for the
 *   tests that restore a dump into it (Dumps); null skips them.
 * - textRuleMissing() (default null): a reason the store cannot compare by the exact-comparison
 *   text rule (a MySQL server without an accent-sensitive, case-insensitive collation, none of
 *   MysqlDialect::MATCH_COLLATIONS; matching does not depend on it); the exact-comparison tests
 *   then skip with it.
 * - accentFreeMatchingMissing() (default null, @since 0.84.0): a reason the store cannot ignore
 *   accents in LIKE, CONTAINS and search() (the rule since 0.78.1; a PostgreSQL without the
 *   unaccent extension, say); the tests of that rule then skip with it. Everything else about
 *   matching (case, ß, the dot of İ) is still tested.
 *
 * Capabilities are claimed by implementing their interface, and their tests are skipped otherwise:
 * - RunsSql (@since 0.78): rawQuery(), execute() and dialect() tests.
 * - Transactions (@since 0.78): transaction() commits, rolls back and rethrows, joins an open one.
 * - AtomicCounters (@since 0.78): increment() inserts a missing row, adds to a stored one,
 *   restarts when the CounterReset field is below its bound (exactly at the boundary too),
 *   concurrent increments lose no count (with reopenDriver(), pcntl and posix), and (@since 0.90)
 *   a count past the 64-bit whole numbers throws an OverflowException naming the counter and
 *   writes nothing (a PdoDriver whose dialect is no Driver\FailsOverflow is not held to it).
 * - Maintenance (@since 0.78): check() finds a sound store sound, compact() keeps every record and
 *   the text rule, and refuses inside a transaction.
 * - Dumps (@since 0.78): a dump() restored into emptyDriver() holds the same records, compared by
 *   the same rule; restore() refuses a store that holds tables.
 * - RankedSearch (@since 0.78): score() ranks the better match higher, gives every given id a
 *   score (0.0 for an unmatched or unknown one); canScore() is true only for the declared fields.
 */
abstract class StorageDriverContract extends TestCase
{
    /** The driver under test, on an empty store. */
    abstract protected function createDriver(): StorageDriver;

    /**
     * Prepare the store for $type (see the class docblock).
     *
     * @param array<string, 'exact'|'text'|'short_text'|'number'|'boolean'|'json'> $fields the id field first
     */
    abstract protected function createType(string $type, array $fields): void;

    /** Whether save() with an empty id makes the store generate one, read with lastInsertId(). */
    protected function supportsAutoIds(): bool
    {
        return true;
    }

    /**
     * A second driver on the same store as createDriver()'s, for a forked child process; null
     * (the default) skips the tests that need one. Called in the child, after the fork.
     */
    protected function reopenDriver(): ?StorageDriver
    {
        return null;
    }

    /**
     * A driver on a second, empty store of the same kind as createDriver()'s (a new database
     * file, an empty database), for the tests that restore a dump into it; null (the default)
     * skips them.
     *
     * @since 0.78
     */
    protected function emptyDriver(): ?StorageDriver
    {
        return null;
    }

    /**
     * Make $fields of $type scorable together (see RankedSearch), as the store needs it: MySQL
     * creates a FULLTEXT index over exactly those columns. Called after createType(). The default
     * does nothing.
     *
     * @since 0.78
     *
     * @param list<string> $fields
     */
    protected function declareFullText(string $type, array $fields): void
    {
    }

    /**
     * A unique index over $field of $type, as the store makes one (called after createType()), for
     * the unique tests of a store that guards unique fields itself (UniqueIndexes). The default
     * skips them.
     *
     * @since 0.78
     */
    protected function declareUnique(string $type, string $field): void
    {
        $this->markTestSkipped('The store makes no unique index of its own (DataManager checks unique fields on it; UniqueScenarios pins that).');
    }

    /**
     * Why the store cannot compare text fields by the text rule, or null (the default) when it
     * can. The exact-comparison tests skip with the reason.
     *
     * @since 0.78
     */
    protected function textRuleMissing(): ?string
    {
        return null;
    }

    /**
     * Why the store cannot ignore accents when matching text (LIKE, CONTAINS, search(), loose
     * search), or null (the default) when it can. The tests of the accent-free rule skip with it.
     *
     * @since 0.84.0
     */
    protected function accentFreeMatchingMissing(): ?string
    {
        return null;
    }

    private StorageDriver $driver;

    protected function setUp(): void
    {
        parent::setUp();
        $this->driver = $this->createDriver();
    }

    // --- records ---------------------------------------------------------------------------

    public function test_a_string_round_trips_exactly(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'Grüße, 世界 👋 "quoted" \'single\' <tag> & \\ back']);

        $this->assertSame('Grüße, 世界 👋 "quoted" \'single\' <tag> & \\ back', $this->record('r1')['label']);
    }

    public function test_a_number_round_trips(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'int', ['uuid' => 'int', 'amount' => 42]);
        $this->driver->save('records', 'float', ['uuid' => 'float', 'amount' => 12.5]);
        $this->driver->save('records', 'negative', ['uuid' => 'negative', 'amount' => -3]);

        $this->assertNumber(42, $this->record('int')['amount'] ?? null);
        $this->assertNumber(12.5, $this->record('float')['amount'] ?? null);
        $this->assertNumber(-3, $this->record('negative')['amount'] ?? null);
    }

    public function test_a_boolean_round_trips(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'yes', ['uuid' => 'yes', 'active' => true]);
        $this->driver->save('records', 'no', ['uuid' => 'no', 'active' => false]);

        $this->assertBoolean(true, $this->record('yes')['active'] ?? null);
        $this->assertBoolean(false, $this->record('no')['active'] ?? null);
    }

    /** @return list<string> the ids of records matching $query, sorted */
    private function recordIds(Query $query): array
    {
        $ids = array_map(static fn (array $row): string => (string) $row['uuid'], $this->driver->findMany('records', $query)->items());
        sort($ids);

        return $ids;
    }

    /** A number equals the same value given as text, as SQL compares a number column (0.78). */
    public function test_equality_matches_a_number_given_as_text(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'two', ['uuid' => 'two', 'amount' => 2]);
        $this->driver->save('records', 'half', ['uuid' => 'half', 'amount' => 2.5]);
        $this->driver->save('records', 'none', ['uuid' => 'none', 'amount' => null]);

        $this->assertSame(['two'], $this->recordIds((new Query())->where('amount', '2')));
        $this->assertSame(['two'], $this->recordIds((new Query())->where('amount', '02')));
        $this->assertSame(['two'], $this->recordIds((new Query())->where('amount', 2)));
        $this->assertSame(['half'], $this->recordIds((new Query())->where('amount', '2.5')));
        $this->assertSame(['two'], $this->recordIds((new Query())->whereAny([['field' => 'amount', 'operator' => '=', 'value' => '2']])));
        $this->assertSame(['half', 'two'], $this->recordIds((new Query())->where('amount', '9')->orWhere('amount', '2')->orWhere('amount', '2.5')));
        $this->assertSame([], $this->recordIds((new Query())->where('amount', '7')));
    }

    /** IN and NOT IN compare as = does: a number equals the same value given as text (0.78). */
    public function test_in_matches_a_number_given_as_text(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'two', ['uuid' => 'two', 'amount' => 2]);
        $this->driver->save('records', 'half', ['uuid' => 'half', 'amount' => 2.5]);
        $this->driver->save('records', 'none', ['uuid' => 'none', 'amount' => null]);

        $this->assertSame(['two'], $this->recordIds((new Query())->where('amount', 'IN', ['02'])));
        $this->assertSame(['half', 'two'], $this->recordIds((new Query())->where('amount', 'IN', ['2.50', 2])));
        $this->assertSame(['two'], $this->recordIds((new Query())->whereAny([['field' => 'amount', 'operator' => 'IN', 'value' => ['02']]])));
        $this->assertSame(['half'], $this->recordIds((new Query())->where('amount', 'NOT IN', ['02'])), 'a NULL field is never in or not in');
    }

    public function test_inequality_of_a_number_given_as_text(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'two', ['uuid' => 'two', 'amount' => 2]);
        $this->driver->save('records', 'half', ['uuid' => 'half', 'amount' => 2.5]);
        $this->driver->save('records', 'none', ['uuid' => 'none', 'amount' => null]);

        $this->assertSame(['half'], $this->recordIds((new Query())->where('amount', '!=', '2')), 'a NULL field is never "not equal"');
        $this->assertSame(['two'], $this->recordIds((new Query())->where('amount', '<>', '2.5')));
        $this->assertSame(['half', 'two'], $this->recordIds((new Query())->where('amount', '!=', '7')));
    }

    /** A yes/no value equals 1/0 given as a number or as text, as SQL compares its stored 1/0 (0.78). */
    public function test_equality_matches_a_boolean_given_as_one_or_zero(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'yes', ['uuid' => 'yes', 'active' => true]);
        $this->driver->save('records', 'no', ['uuid' => 'no', 'active' => false]);

        foreach (['1', 1, true] as $given) {
            $this->assertSame(['yes'], $this->recordIds((new Query())->where('active', $given)), var_export($given, true));
        }
        foreach (['0', 0, false] as $given) {
            $this->assertSame(['no'], $this->recordIds((new Query())->where('active', $given)), var_export($given, true));
        }
        $this->assertSame(['yes'], $this->recordIds((new Query())->whereAny([['field' => 'active', 'operator' => '=', 'value' => '1']])));
        $this->assertSame(['no', 'yes'], $this->recordIds((new Query())->where('active', '1')->orWhere('active', '0')));
    }

    public function test_inequality_of_a_boolean_given_as_one_or_zero(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'yes', ['uuid' => 'yes', 'active' => true]);
        $this->driver->save('records', 'no', ['uuid' => 'no', 'active' => false]);

        $this->assertSame(['no'], $this->recordIds((new Query())->where('active', '!=', '1')));
        $this->assertSame(['yes'], $this->recordIds((new Query())->where('active', '<>', 0)));
    }

    /** A yes/no value is in a list as '1' or '0', as SQL stores it (0.78: JSON files hold true/false). */
    public function test_a_boolean_is_in_a_list_as_one_or_zero(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'yes', ['uuid' => 'yes', 'active' => true]);
        $this->driver->save('records', 'no', ['uuid' => 'no', 'active' => false]);

        $in = fn (array $values): array => array_map(
            static fn (array $row): string => (string) $row['uuid'],
            $this->driver->findMany('records', (new Query())->where('active', 'IN', $values))->items(),
        );
        $any = fn (array $values): array => array_map(
            static fn (array $row): string => (string) $row['uuid'],
            $this->driver->findMany('records', (new Query())->whereAny([['field' => 'active', 'operator' => 'IN', 'value' => $values]]))->items(),
        );
        $this->assertSame(['yes'], $in(['1']));
        $this->assertSame(['no'], $in(['0']));
        $this->assertSame(['no'], $in([0]));
        $this->assertSame(['yes'], $any(['1']));
        $this->assertSame(['no'], $any(['0']));
    }

    public function test_a_json_field_round_trips(): void
    {
        $this->createRecords();
        $meta = ['tags' => ['a', 'b'], 'size' => ['w' => 3, 'h' => 4], 'note' => 'Grüße'];
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'meta' => $meta]);

        $stored = $this->record('r1')['meta'] ?? null;
        $decoded = is_string($stored) ? json_decode($stored, true) : $stored;
        $this->assertSame(self::keysSorted($meta), is_array($decoded) ? self::keysSorted($decoded) : $decoded, 'a json field reads back as the saved array, or as JSON text of it (object key order may differ)');
    }

    /**
     * A list of ids (a multiple relation or asset since 0.89), the same list as JSON text (stored
     * before 0.89) and a single id live side by side in one field: each reads back as saved (a list
     * as that list or as JSON text of it), and HAS finds every shape.
     */
    public function test_has_finds_ids_in_a_list_in_old_json_text_and_in_a_single_id(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'new', ['uuid' => 'new', 'meta' => ['a1', 'a2']]);
        $this->driver->save('records', 'old', ['uuid' => 'old', 'meta' => '["a1","a3"]']);
        $this->driver->save('records', 'one', ['uuid' => 'one', 'meta' => 'a3']);

        $list = static fn (mixed $v): mixed => is_string($v) && str_starts_with($v, '[') ? json_decode($v, true) : $v;
        $this->assertSame(['a1', 'a2'], $list($this->record('new')['meta'] ?? null));
        $this->assertSame(['a1', 'a3'], $list($this->record('old')['meta'] ?? null));
        $this->assertSame('a3', $this->record('one')['meta'] ?? null);

        $has = fn (array $ids): array => $this->sortedIds($this->driver->findMany('records', (new Query())->whereAny([['field' => 'meta', 'operator' => 'HAS', 'value' => $ids]])));
        $this->assertSame(['new', 'old'], $has(['a1']));
        $this->assertSame(['old', 'one'], $has(['a3']));
        $this->assertSame(['new'], $has(['a2']));
        $this->assertSame(['new', 'old', 'one'], $has(['a2', 'a3']));
        $this->assertSame([], $has(['a4']));
    }

    public function test_null_round_trips_in_every_kind(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => null, 'amount' => null, 'active' => null, 'meta' => null]);

        $row = $this->record('r1');
        foreach (['label', 'amount', 'active', 'meta'] as $field) {
            $this->assertNull($row[$field] ?? null, "a null {$field} reads back as null");
        }
    }

    public function test_saving_an_existing_id_again_updates_the_record(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'First', 'amount' => 1]);
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'Second', 'amount' => 2]);

        $row = $this->record('r1');
        $this->assertSame('Second', $row['label'], 'saving an existing id again writes the new values');
        $this->assertNumber(2, $row['amount'] ?? null);
        $this->assertSame(1, $this->driver->findMany('records', new Query())->total(), 'saving an existing id adds no second record');
    }

    /** @since 0.78 a save writes the fields it is given and keeps the others. */
    public function test_a_partial_save_keeps_the_other_fields(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'One', 'amount' => 1, 'active' => true]);
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'amount' => 2]);

        $row = $this->record('r1');
        $this->assertSame('One', $row['label'] ?? null, 'a field the save does not name keeps its stored value');
