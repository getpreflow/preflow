<?php

declare(strict_types=1);

namespace Preflow\Testing\Contract;

use PHPUnit\Framework\TestCase;
use Preflow\Data\Query;
use Preflow\Data\ResultSet;
use Preflow\Data\SortDirection;
use Preflow\Data\StorageDriver;

/**
 * What every StorageDriver does, as tests. Extend it, implement the two hooks, and run it with
 * PHPUnit:
 *
 *     final class MyDriverContractTest extends StorageDriverContract
 *     {
 *         protected function createDriver(): StorageDriver
 *         {
 *             return new MyDriver(...);
 *         }
 *
 *         protected function createType(string $type, array $fields): void
 *         {
 *             // e.g. CREATE TABLE $type (...)
 *         }
 *     }
 *
 * - createDriver() is called once per test, in setUp(), before any createType(). Each test needs
 *   an empty store: a fresh in-memory database, a temporary directory, or a database the test
 *   class empties in setUp() and tearDown().
 * - createType() prepares the store for one type (an SQL driver creates the table; a store
 *   without a schema does nothing). $fields maps each field name to `string`, `number`,
 *   `boolean` or `json`. The first field is the id field and the primary key: a `string` id is
 *   given by the caller; a `number` id is generated by the store (auto increment) and only
 *   used when supportsAutoIds() is true. Every other field takes null.
 *
 * Values read back may come in the store's own representation, as DataManager accepts them:
 * a number as an int, a float or a numeric string; a boolean as true/false, 1/0 or "1"/"0";
 * a `json` field (saved as an array) as that array or as JSON text; null as null or a missing
 * key. Strings come back exactly as saved.
 *
 * Optional hooks, for stores that cannot do something generic:
 * - supportsAutoIds() (default true): false skips the test that saves with an empty id and
 *   reads the new id from lastInsertId() (the JSON file driver needs the id from the caller).
 * - supportsRawQuery() (default true): false skips the rawQuery() test (SQL drivers only).
 */
abstract class StorageDriverContract extends TestCase
{
    /** The driver under test, on an empty store. */
    abstract protected function createDriver(): StorageDriver;

    /**
     * Prepare the store for $type (see the class docblock).
     *
     * @param array<string, 'string'|'number'|'boolean'|'json'> $fields the id field first
     */
    abstract protected function createType(string $type, array $fields): void;

    /** Whether save() with an empty id makes the store generate one, read with lastInsertId(). */
    protected function supportsAutoIds(): bool
    {
        return true;
    }

    /** Whether rawQuery() runs SQL against the store. */
    protected function supportsRawQuery(): bool
    {
        return true;
    }

    private StorageDriver $driver;

    protected function setUp(): void
    {
        parent::setUp();
        $this->driver = $this->createDriver();
    }

    // --- records ---------------------------------------------------------------------------

    public function test_a_string_round_trips_exactly(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'Grüße, 世界 👋 "quoted" \'single\' <tag> & \\ back']);

        $this->assertSame('Grüße, 世界 👋 "quoted" \'single\' <tag> & \\ back', $this->record('r1')['label']);
    }

    public function test_a_number_round_trips(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'int', ['uuid' => 'int', 'amount' => 42]);
        $this->driver->save('records', 'float', ['uuid' => 'float', 'amount' => 12.5]);
        $this->driver->save('records', 'negative', ['uuid' => 'negative', 'amount' => -3]);

        $this->assertNumber(42, $this->record('int')['amount'] ?? null);
        $this->assertNumber(12.5, $this->record('float')['amount'] ?? null);
        $this->assertNumber(-3, $this->record('negative')['amount'] ?? null);
    }

    public function test_a_boolean_round_trips(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'yes', ['uuid' => 'yes', 'active' => true]);
        $this->driver->save('records', 'no', ['uuid' => 'no', 'active' => false]);

        $this->assertBoolean(true, $this->record('yes')['active'] ?? null);
        $this->assertBoolean(false, $this->record('no')['active'] ?? null);
    }

    public function test_a_json_field_round_trips(): void
    {
        $this->createRecords();
        $meta = ['tags' => ['a', 'b'], 'size' => ['w' => 3, 'h' => 4], 'note' => 'Grüße'];
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'meta' => $meta]);

        $stored = $this->record('r1')['meta'] ?? null;
        $decoded = is_string($stored) ? json_decode($stored, true) : $stored;
        $this->assertSame($meta, $decoded, 'a json field reads back as the saved array, or as JSON text of it');
    }

    public function test_null_round_trips_in_every_kind(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => null, 'amount' => null, 'active' => null, 'meta' => null]);

        $row = $this->record('r1');
        foreach (['label', 'amount', 'active', 'meta'] as $field) {
            $this->assertNull($row[$field] ?? null, "a null {$field} reads back as null");
        }
    }

    public function test_saving_an_existing_id_again_updates_the_record(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'First', 'amount' => 1]);
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'Second', 'amount' => 2]);

        $row = $this->record('r1');
        $this->assertSame('Second', $row['label'], 'saving an existing id again writes the new values');
        $this->assertNumber(2, $row['amount'] ?? null);
        $this->assertSame(1, $this->driver->findMany('records', new Query())->total(), 'saving an existing id adds no second record');
    }

    public function test_exists_tells_saved_from_missing_ids(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'One']);

        $this->assertTrue($this->driver->exists('records', 'r1'));
        $this->assertFalse($this->driver->exists('records', 'missing'));
        $this->assertNull($this->driver->findOne('records', 'missing'), 'findOne() of a missing id is null');
    }

    public function test_delete_removes_the_record(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'One']);
        $this->driver->save('records', 'r2', ['uuid' => 'r2', 'label' => 'Two']);

        $this->driver->delete('records', 'r1');

        $this->assertFalse($this->driver->exists('records', 'r1'));
        $this->assertNull($this->driver->findOne('records', 'r1'));
        $this->assertTrue($this->driver->exists('records', 'r2'), 'delete() removes only the record with that id');
    }

    public function test_deleting_a_missing_id_is_not_an_error(): void
    {
        $this->createRecords();

        $this->driver->delete('records', 'missing');

        $this->assertFalse($this->driver->exists('records', 'missing'));
    }

    public function test_a_custom_id_field(): void
    {
        $this->createType('things', ['code' => 'string', 'title' => 'string']);
        $this->driver->save('things', 'abc', ['code' => 'abc', 'title' => 'First'], 'code');
        $this->driver->save('things', 'abc', ['code' => 'abc', 'title' => 'Second'], 'code');
        $this->driver->save('things', 'xyz', ['code' => 'xyz', 'title' => 'Other'], 'code');

        $this->assertSame('Second', $this->driver->findOne('things', 'abc', 'code')['title'] ?? null, 'a record is found and updated by the given id field');
        $this->assertTrue($this->driver->exists('things', 'abc', 'code'));
        $this->driver->delete('things', 'abc', 'code');
        $this->assertFalse($this->driver->exists('things', 'abc', 'code'));
        $this->assertTrue($this->driver->exists('things', 'xyz', 'code'));
    }

    public function test_an_empty_id_gets_a_generated_id_from_last_insert_id(): void
    {
        if (!$this->supportsAutoIds()) {
            $this->markTestSkipped('The driver generates no ids (supportsAutoIds() is false).');
        }
        $this->createType('counters', ['id' => 'number', 'name' => 'string']);

        $this->driver->save('counters', 0, ['name' => 'First'], 'id');
        $first = $this->driver->lastInsertId();
        $this->driver->save('counters', '', ['name' => 'Second'], 'id');
        $second = $this->driver->lastInsertId();

        $this->assertTrue(is_int($first) || (is_string($first) && $first !== ''), 'lastInsertId() gives the id the store generated');
        $this->assertNotEquals($first, $second, 'each insert gets its own id');
        $this->assertSame('First', $this->driver->findOne('counters', $first, 'id')['name'] ?? null);
        $this->assertSame('Second', $this->driver->findOne('counters', $second, 'id')['name'] ?? null);
    }

    public function test_raw_query(): void
    {
        if (!$this->supportsRawQuery()) {
            $this->markTestSkipped('The driver runs no raw SQL (supportsRawQuery() is false).');
        }
        $this->seedItems();

        $rows = $this->driver->rawQuery('SELECT title FROM items WHERE uuid = ?', ['2']);

        $this->assertSame([['title' => 'Banana']], $rows);
    }

    // --- findMany ----------------------------------------------------------------------------

    public function test_find_many_without_conditions_returns_every_record(): void
    {
        $this->seedItems();

        $result = $this->driver->findMany('items', new Query());

        $this->assertInstanceOf(ResultSet::class, $result);
        $this->assertSame(['1', '2', '3'], $this->sortedIds($result));
        $this->assertSame(3, $result->total());
    }

    public function test_where_equals(): void
    {
        $this->seedItems();

        $this->assertSame(['2'], $this->ids((new Query())->where('title', 'Banana')), 'where(field, value) compares with =');
        $this->assertSame(['2'], $this->ids((new Query())->where('title', '=', 'Banana')));
        $this->assertSame([], $this->ids((new Query())->where('title', 'Durian')));
    }

    public function test_where_not_equals(): void
    {
        $this->seedItems();

        $this->assertSame(['1', '3'], $this->ids((new Query())->where('title', '!=', 'Banana')));
        $this->assertSame(['1', '3'], $this->ids((new Query())->where('title', '<>', 'Banana')));
    }

    public function test_where_compares_numbers_as_numbers(): void
    {
        $this->seedItems(); // prices: 1 → 1.5, 2 → 10, 3 → 2

        $this->assertSame(['1', '3'], $this->ids((new Query())->where('price', '<', 10)));
        $this->assertSame(['2'], $this->ids((new Query())->where('price', '>', 2)));
        $this->assertSame(['1', '3'], $this->ids((new Query())->where('price', '<=', 2)));
        $this->assertSame(['2', '3'], $this->ids((new Query())->where('price', '>=', 2)));
    }

    public function test_where_like_and_not_like(): void
    {
        $this->seedItems();

        $this->assertSame(['2'], $this->ids((new Query())->where('title', 'like', 'b%')), 'LIKE ignores case, % matches any text');
        $this->assertSame(['1', '2'], $this->ids((new Query())->where('title', 'LIKE', '%a%')));
        $this->assertSame(['2', '3'], $this->ids((new Query())->where('title', 'NOT LIKE', 'a%')));
    }

    public function test_where_in_and_not_in(): void
    {
        $this->seedItems();

        $this->assertSame(['1', '3'], $this->ids((new Query())->where('title', 'IN', ['Apple', 'Cherry'])));
        $this->assertSame(['1', '3'], $this->ids((new Query())->where('title', 'in', ['Apple', 'Cherry'])), 'operators take any case');
        $this->assertSame(['2'], $this->ids((new Query())->where('title', 'NOT IN', ['Apple', 'Cherry'])));
        $this->assertSame([], $this->ids((new Query())->where('title', 'IN', [])), 'an empty IN matches nothing');
        $this->assertSame(['1', '2', '3'], $this->ids((new Query())->where('title', 'NOT IN', [])), 'an empty NOT IN matches everything');
        $this->assertSame(['1', '2', '3'], $this->ids((new Query())->where('tags', 'NOT IN', [])), 'an empty NOT IN takes null fields too');
        $this->assertSame(['3'], $this->ids((new Query())->where('tags', 'NOT IN', ['x'])), 'a NOT IN never takes a null field');
    }

    public function test_where_null(): void
    {
        $this->seedItems(); // tags: 1 → null, 2 → x, 3 → y

        $this->assertSame(['1'], $this->ids((new Query())->where('tags', null)), 'where(field, null) is IS NULL');
        $this->assertSame(['1'], $this->ids((new Query())->where('tags', '=', null)));
        $this->assertSame(['2', '3'], $this->ids((new Query())->where('tags', '!=', null)), '!= null is IS NOT NULL');
        $this->assertSame(['2', '3'], $this->ids((new Query())->where('tags', '<>', null)));
        $this->assertSame(1, $this->driver->findMany('items', (new Query())->where('tags', null))->total());
    }

    public function test_or_where(): void
    {
        $this->seedItems();

        $this->assertSame(['1', '2'], $this->ids((new Query())->where('title', 'Apple')->orWhere('title', 'Banana')));
        $this->assertSame(['1', '3'], $this->ids((new Query())->where('title', 'Cherry')->orWhere('tags', null)));
        $this->assertSame(['2', '3'], $this->ids((new Query())->where('price', '>', 5)->orWhere('title', 'LIKE', 'c%')));
    }

    public function test_where_and_or_where_combine(): void
    {
        $this->seedItems();

        // title = Apple AND price < 2, OR title = Cherry: Apple (1.5) and Cherry.
        $query = (new Query())->where('title', 'Apple')->where('price', '<', 2)->orWhere('title', 'Cherry');

        $this->assertSame(['1', '3'], $this->ids($query));
    }

    public function test_order_by_a_string_field(): void
    {
        $this->seedItems();

        $this->assertSame(['1', '2', '3'], $this->orderedIds((new Query())->orderBy('title')));
        $this->assertSame(['3', '2', '1'], $this->orderedIds((new Query())->orderBy('title', SortDirection::Desc)));
    }

    public function test_order_by_a_number_field_sorts_numerically(): void
    {
        $this->seedItems(); // prices: 1 → 1.5, 2 → 10, 3 → 2

        $this->assertSame(['1', '3', '2'], $this->orderedIds((new Query())->orderBy('price')));
        $this->assertSame(['2', '3', '1'], $this->orderedIds((new Query())->orderBy('price', SortDirection::Desc)));
    }

    public function test_limit_and_offset_with_the_total_of_all_matches(): void
    {
        $this->seedItems();

        $first = $this->driver->findMany('items', (new Query())->orderBy('title')->limit(2));
        $this->assertSame(['1', '2'], $this->idsInOrder($first));
        $this->assertSame(3, $first->total(), 'total() counts every match, not just the page');
        $this->assertCount(2, $first);

        $second = $this->driver->findMany('items', (new Query())->orderBy('title')->limit(2)->offset(2));
        $this->assertSame(['3'], $this->idsInOrder($second));
        $this->assertSame(3, $second->total());

        $middle = $this->driver->findMany('items', (new Query())->orderBy('title')->limit(1)->offset(1));
        $this->assertSame(['2'], $this->idsInOrder($middle));
    }

    public function test_total_counts_the_matches_of_the_conditions(): void
    {
        $this->seedItems();

        $result = $this->driver->findMany('items', (new Query())->where('title', '!=', 'Banana')->limit(1));

        $this->assertCount(1, $result);
        $this->assertSame(2, $result->total());
    }

    // --- helpers ----------------------------------------------------------------------------

    private function createRecords(): void
    {
        $this->createType('records', ['uuid' => 'string', 'label' => 'string', 'amount' => 'number', 'active' => 'boolean', 'meta' => 'json']);
    }

    /** The rows WhereScenarios uses (uuid, title, tags), with a price each. */
    private function seedItems(): void
    {
        $this->createType('items', ['uuid' => 'string', 'title' => 'string', 'tags' => 'string', 'price' => 'number']);
        $this->driver->save('items', '1', ['uuid' => '1', 'title' => 'Apple', 'tags' => null, 'price' => 1.5]);
        $this->driver->save('items', '2', ['uuid' => '2', 'title' => 'Banana', 'tags' => 'x', 'price' => 10]);
        $this->driver->save('items', '3', ['uuid' => '3', 'title' => 'Cherry', 'tags' => 'y', 'price' => 2]);
    }

    /** @return array<string, mixed> */
    private function record(string $id): array
    {
        $row = $this->driver->findOne('records', $id);
        $this->assertIsArray($row, "findOne() finds the saved record {$id}");

        return $row;
    }

    /** @return list<string> the matching item ids, sorted */
    private function ids(Query $query): array
    {
        return $this->sortedIds($this->driver->findMany('items', $query));
    }

    /** @return list<string> the item ids in the order findMany() returns them */
    private function orderedIds(Query $query): array
    {
        return $this->idsInOrder($this->driver->findMany('items', $query));
    }

    /** @return list<string> */
    private function idsInOrder(ResultSet $result): array
    {
        return array_map('strval', array_column($result->items(), 'uuid'));
    }

    /** @return list<string> */
    private function sortedIds(ResultSet $result): array
    {
        $ids = $this->idsInOrder($result);
        sort($ids);

        return $ids;
    }

    private function assertNumber(int|float $expected, mixed $actual): void
    {
        $this->assertTrue(is_int($actual) || is_float($actual) || (is_string($actual) && is_numeric($actual)), sprintf('a number reads back as a number, got %s', var_export($actual, true)));
        $this->assertEqualsWithDelta((float) $expected, (float) $actual, 1e-9);
    }

    private function assertBoolean(bool $expected, mixed $actual): void
    {
        $accepted = $expected ? [true, 1, '1'] : [false, 0, '0'];
        $this->assertContains($actual, $accepted, sprintf('a boolean %s reads back as one of true/1/"1" or false/0/"0", got %s', var_export($expected, true), var_export($actual, true)));
    }
}
