    public function test_dialect_quotes_identifiers_the_store_accepts(): void
    {
        $sql = $this->runsSql();
        $this->seedItems();
        $q = $sql->dialect()->quoteIdentifier(...);

        $rows = $sql->rawQuery('SELECT ' . $q('title') . ' FROM ' . $q('items') . ' WHERE uuid = ?', ['2']);

