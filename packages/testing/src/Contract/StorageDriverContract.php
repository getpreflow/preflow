    /** @since 0.78 */
    public function test_a_field_saved_as_null_is_stored_as_null(): void
    {
        $this->createRecords();
        $this->driver->save('records', 'r1', ['uuid' => 'r1', 'label' => 'One', 'amount' => 1]);
