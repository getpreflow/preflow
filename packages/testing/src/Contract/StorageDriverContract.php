    private function runsSql(): RunsSql
    {
        if (!$this->driver instanceof RunsSql) {
            $this->markTestSkipped('The driver does not implement RunsSql.');
        }

        return $this->driver;
    }

    // --- table existence (DescribesColumns, @since 0.78) ---------------------------------------

    public function test_has_table_tells_a_made_type_from_a_missing_one(): void
