<?php

declare(strict_types=1);

namespace Preflow\Data\Tests;

use PHPUnit\Framework\Attributes\DataProvider;
use Preflow\Data\Attributes\Entity;
use Preflow\Data\Attributes\Field;
use Preflow\Data\Attributes\Id;
use Preflow\Data\DataManager;
use Preflow\Data\Model;

#[Entity(table: 'tallies', storage: 'default')]
class TallyRow extends Model
{
    #[Id]
    public int $id = 0;

    #[Field]
    public string $label = '';
}

#[Entity(table: 'tallies', storage: 'default')]
class NullableTallyRow extends Model
{
    #[Id]
    public ?int $id = null;

    #[Field]
    public string $label = '';
}

/** A class-backed type with an int id: its type comes from the class (TypeRegistry). */
#[Entity(table: 'typed_tallies', storage: 'default', type: 'typed_tallies')]
class TypedTallyRow extends Model
{
    #[Id]
    public int $id = 0;

    #[Field]
    public ?string $label = null;
}

/**
 * insert() on a model with an int #[Id] (since 0.80.0): a non-zero id the caller set is written as
 * it is and only while no record has it (a second insert() of it throws the duplicate-id error,
 * insertIgnoring() skips it); an id left at 0 is still generated by the storage. The using test
 * gives kinds() (a data provider) and manager($kind, $typed), and says which kinds generate ids.
 */
trait IntIdInsertScenarios
{
    /** A manager over one storage named 'default'; $typed: TypedTallyRow is a class-backed type. */
    abstract protected function manager(string $kind, bool $typed = false): DataManager;

    abstract protected function generatesIds(string $kind): bool;

    /** @return iterable<string, array{string, bool}> */
    abstract public static function kindsAndModels(): iterable;

    private function tally(bool $typed, int $id, string $label): TallyRow|TypedTallyRow
    {
        $row = $typed ? new TypedTallyRow() : new TallyRow();
        $row->id = $id;
        $row->label = $label;

        return $row;
    }

    #[DataProvider('kindsAndModels')]
    public function test_insert_keeps_a_given_int_id(string $kind, bool $typed): void
    {
        $dm = $this->manager($kind, $typed);
        $row = $this->tally($typed, 7, 'seven');

        $dm->insert($row);

        $this->assertSame(7, $row->id, 'the given id stays on the model');
        $this->assertSame('seven', $dm->find($row::class, 7)?->label, 'the record is stored under the given id');
    }

    #[DataProvider('kindsAndModels')]
    public function test_a_second_insert_of_a_given_int_id_throws_and_keeps_the_first(string $kind, bool $typed): void
    {
        $dm = $this->manager($kind, $typed);
        $dm->insert($this->tally($typed, 7, 'first'));

        $error = null;
        try {
            $dm->insert($this->tally($typed, 7, 'second'));
        } catch (\RuntimeException $e) {
            $error = $e;
        }
        $this->assertNotNull($error, 'a second insert() of the id throws');
        $this->assertStringContainsString('a record with this id exists', $error->getMessage());
        $this->assertSame('first', $dm->find($typed ? TypedTallyRow::class : TallyRow::class, 7)?->label, 'the stored record is untouched');
    }

    #[DataProvider('kindsAndModels')]
    public function test_insert_ignoring_skips_a_given_int_id_that_exists(string $kind, bool $typed): void
    {
        $dm = $this->manager($kind, $typed);

        $this->assertTrue($dm->insertIgnoring($this->tally($typed, 7, 'first')));
        $this->assertFalse($dm->insertIgnoring($this->tally($typed, 7, 'second')));
        $this->assertSame('first', $dm->find($typed ? TypedTallyRow::class : TallyRow::class, 7)?->label);
    }

    #[DataProvider('kindsAndModels')]
    public function test_an_id_left_at_zero_is_still_generated(string $kind, bool $typed): void
    {
        if (!$this->generatesIds($kind)) {
            $this->markTestSkipped('This storage generates no ids.');
        }
        $dm = $this->manager($kind, $typed);
        $dm->insert($this->tally($typed, 7, 'given'));

        $auto = $this->tally($typed, 0, 'generated');
        $dm->insert($auto);

        $this->assertGreaterThan(0, $auto->id, 'the storage gave an id');
        $this->assertNotSame(7, $auto->id);
        $this->assertSame('generated', $dm->find($auto::class, $auto->id)?->label);
        $this->assertSame('given', $dm->find($auto::class, 7)?->label, 'the given record is untouched');
    }

    #[DataProvider('kindsAndModels')]
    public function test_an_id_left_at_null_is_still_generated(string $kind, bool $typed): void
    {
        if ($typed || !$this->generatesIds($kind)) {
            $this->markTestSkipped('Plain models on storage that generates ids only.');
        }
        $dm = $this->manager($kind);
        $given = new NullableTallyRow();
        $given->id = 7;
        $given->label = 'given';
        $dm->insert($given);

        $auto = new NullableTallyRow();
        $auto->label = 'generated';
        $dm->insert($auto);

        $this->assertNotNull($auto->id, 'the storage gave an id');
        $this->assertNotSame(7, $auto->id);
        $this->assertSame('generated', $dm->find(NullableTallyRow::class, $auto->id)?->label);
        $this->assertSame('given', $dm->find(NullableTallyRow::class, 7)?->label, 'the given record is untouched');
    }
}
